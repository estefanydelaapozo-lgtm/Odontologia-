package routes

import (
	"github.com/gofiber/fiber/v2"
	"sigo-dental/backend/controllers"
	"sigo-dental/backend/middleware"
	"sigo-dental/backend/repository"
)

// SetupRoutes is the only place where HTTP endpoints are registered.
func SetupRoutes(app *fiber.App, secret []byte, repo repository.DBRepository) {
	app.Get("/api/health", controllers.Health)
	app.Post("/api/payment-gateway/webhook", controllers.PaymentGatewayWebhook)
	app.Post("/api/auth/login", controllers.Login)
	api := app.Group("/api", middleware.RequireAuth(secret))
	api.Use(middleware.AuditRequests(repo))
	api.Get("/auth/me", controllers.Me)
	api.Post("/auth/mfa/setup", controllers.SetupMFA)
	api.Post("/auth/mfa/confirm", controllers.ConfirmMFA)
	admin := middleware.RequireRoles("admin")
	mfa := middleware.RequireMFA()
	api.Get("/patient-appointment-requests", middleware.RequireRoles("paciente", "admin", "recepcionista"), controllers.PatientAppointmentRequests)
	api.Post("/patient-appointment-requests", middleware.RequireRoles("paciente"), controllers.CreatePatientAppointmentRequest)
	api.Patch("/patient-appointment-requests/:id", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.ReviewPatientAppointmentRequest)
	api.Get("/users", admin, mfa, controllers.ListUsers)
	api.Post("/users", admin, mfa, controllers.CreateUser)
	api.Get("/patients", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), mfa, controllers.ListPatients)
	api.Post("/patients", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.CreatePatient)
	api.Put("/patients/:id", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.UpdatePatient)
	clinical := middleware.RequireRoles("admin", "odontologo")
	api.Get("/patients/:id/odontogram", clinical, mfa, controllers.GetOdontogram)
	api.Put("/patients/:id/odontogram", clinical, mfa, controllers.SaveOdontogram)
	api.Get("/patients/:id/periodontogram", clinical, mfa, controllers.GetPeriodontogram)
	api.Post("/patients/:id/periodontogram", clinical, mfa, controllers.SavePeriodontogram)
	api.Get("/patients/:id/clinical-notes", middleware.RequireRoles("admin", "odontologo", "asistente"), mfa, controllers.ListClinicalNotes)
	api.Get("/patients/:id/files", middleware.RequireRoles("admin", "odontologo", "asistente"), mfa, controllers.ListClinicalFiles)
	api.Post("/patients/:id/files", middleware.RequireRoles("admin", "odontologo", "asistente"), mfa, controllers.UploadClinicalFile)
	api.Get("/clinical-files/:id/download", middleware.RequireRoles("admin", "odontologo", "asistente"), mfa, controllers.DownloadClinicalFile)
	api.Post("/patients/:id/clinical-notes", middleware.RequireRoles("admin", "odontologo"), mfa, controllers.CreateClinicalNote)
	api.Put("/clinical-notes/:id", middleware.RequireRoles("admin", "odontologo"), mfa, controllers.UpdateClinicalNote)
	api.Post("/clinical-notes/:id/sign", middleware.RequireRoles("admin", "odontologo"), mfa, controllers.SignClinicalNote)
	api.Post("/clinical-notes/:id/addenda", middleware.RequireRoles("admin", "odontologo"), mfa, controllers.AddClinicalAddendum)
	api.Get("/consent-templates", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), mfa, controllers.ListConsentTemplates)
	api.Post("/consent-templates", admin, mfa, controllers.CreateConsentTemplate)
	api.Get("/patients/:id/consents", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), mfa, controllers.ListPatientConsents)
	api.Post("/patients/:id/consents", middleware.RequireRoles("admin", "recepcionista", "odontologo"), mfa, controllers.CreatePatientConsent)
	api.Post("/consents/:id/send-otp", middleware.RequireRoles("admin", "recepcionista", "odontologo"), mfa, controllers.SendConsentOTP)
	api.Post("/consents/:id/sign", middleware.RequireRoles("admin", "recepcionista", "odontologo"), mfa, controllers.SignPatientConsent)
	api.Get("/patients/:id/treatment-plans", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), mfa, controllers.ListTreatmentPlans)
	api.Post("/patients/:id/treatment-plans", middleware.RequireRoles("admin", "odontologo"), mfa, controllers.CreateTreatmentPlan)
	api.Post("/treatment-plans/:id/approve", middleware.RequireRoles("admin", "odontologo", "recepcionista"), mfa, controllers.ApproveTreatmentPlan)
	api.Post("/treatments/perform", middleware.RequireRoles("admin", "odontologo"), mfa, controllers.PerformTreatment)
	api.Get("/professionals", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), controllers.ListProfessionals)
	api.Post("/professionals", admin, controllers.CreateProfessional)
	api.Get("/chairs", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), controllers.ListChairs)
	api.Post("/chairs", admin, controllers.CreateChair)
	api.Get("/services", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), controllers.ListServices)
	api.Post("/services", admin, controllers.CreateService)
	api.Get("/appointments", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), mfa, controllers.ListAppointments)
	api.Post("/appointments", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.CreateAppointment)
	api.Patch("/appointments/:id/status", middleware.RequireRoles("admin", "recepcionista", "odontologo", "asistente"), mfa, controllers.UpdateAppointmentStatus)
	api.Get("/invoices", middleware.RequireRoles("admin", "recepcionista", "auditor"), mfa, controllers.ListInvoices)
	api.Post("/invoices", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.CreateInvoice)
	api.Post("/invoices/:id/payments", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.AddPayment)
	api.Post("/invoices/:id/payment-intents", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.CreatePaymentIntent)
	api.Get("/cash/current", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.CurrentCashSession)
	api.Post("/cash/open", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.OpenCashSession)
	api.Post("/cash/close", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.CloseCashSession)
	api.Get("/reports/cash", middleware.RequireRoles("admin", "auditor"), mfa, controllers.CashReport)
	api.Get("/inventory", middleware.RequireRoles("admin", "recepcionista", "asistente"), mfa, controllers.ListInventory)
	api.Post("/inventory", middleware.RequireRoles("admin"), mfa, controllers.CreateInventoryItem)
	api.Post("/inventory/adjust", middleware.RequireRoles("admin", "asistente"), mfa, controllers.AdjustInventory)
	api.Put("/services/:id/materials", middleware.RequireRoles("admin"), mfa, controllers.SetServiceMaterials)
	api.Get("/services/:id/materials", middleware.RequireRoles("admin", "asistente"), mfa, controllers.ListServiceMaterials)
	api.Post("/professional-fee-rules", middleware.RequireRoles("admin"), mfa, controllers.CreateFeeRule)
	api.Get("/settlements", middleware.RequireRoles("admin", "auditor"), mfa, controllers.ListSettlements)
	api.Post("/settlements", middleware.RequireRoles("admin"), mfa, controllers.CreateSettlement)
	// --- Ampliaciones: auditoría, expediente unificado, reportes, usuarios, honorarios, inventario, notificaciones y reprogramación ---
	api.Get("/audit-log", middleware.RequireRoles("admin", "auditor"), mfa, controllers.ListAuditLog)
	api.Get("/patients/:id/record", middleware.RequireRoles("admin", "odontologo", "asistente"), mfa, controllers.PatientRecord)
	api.Get("/reports/:kind", middleware.RequireRoles("admin", "recepcionista", "auditor", "asistente"), mfa, controllers.Report)
	api.Put("/users/:id", admin, mfa, controllers.UpdateUser)
	api.Post("/users/:id/reset-password", admin, mfa, controllers.ResetUserPassword)
	api.Post("/users/:id/reset-mfa", admin, mfa, controllers.ResetUserMFA)
	api.Get("/professional-fee-rules", middleware.RequireRoles("admin", "auditor"), mfa, controllers.ListFeeRules)
	api.Delete("/professional-fee-rules/:id", admin, mfa, controllers.DeactivateFeeRule)
	api.Get("/inventory/movements", middleware.RequireRoles("admin", "asistente", "auditor"), mfa, controllers.ListInventoryMovements)
	api.Get("/notifications", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.ListNotifications)
	api.Put("/appointments/:id", middleware.RequireRoles("admin", "recepcionista"), mfa, controllers.RescheduleAppointment)
	api.Get("/dashboard", middleware.RequireRoles("admin", "recepcionista", "auditor"), mfa, controllers.Dashboard)
}
